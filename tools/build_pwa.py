#!/usr/bin/env python3
"""Builds pwa-files.js, the file list behind the offline (installable) version of the site.

    python3 tools/build_theory.py      runs this at the end of every build
    python3 tools/build_pwa.py         rebuilds only the list
    python3 tools/build_pwa.py --check exits with an error if pwa-files.js is out of date (run before pushing)

pwa-files.js lists every file with a short content hash. The service worker (sw.js) saves the "core" files on a
student's device and, on each update, fetches only the files whose hash changed. If this list is stale, students
keep old copies of changed files, so rebuild it after every change to the site (the GitHub Action does this).

    core     pages, styles, scripts, data, fonts and small images. Saved automatically (about 2 MB).
    img      every image under images/, so the service worker can save images as they are viewed.
    pack     the diagram layers used by the viewer. Saved only when a student taps "Download diagrams".
"""
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from atlas_data import ROOT, load_atlas  # noqa: E402

OUT = os.path.join(ROOT, "pwa-files.js")
CORE_EXT = {".html", ".css", ".js", ".json", ".webmanifest", ".woff2", ".webp", ".svg", ".png", ".ico", ".txt"}
IMG_EXT = {".png", ".webp", ".jpg", ".jpeg", ".gif", ".svg"}
NEVER = {"sw.js", "pwa-files.js"}  # always fetched from the network, never saved by the worker


def digest(path):
    h = hashlib.md5()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:10]


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def core_files():
    out = {}

    def add(path):
        r = rel(path)
        if r in NEVER or os.path.splitext(r)[1].lower() not in CORE_EXT:
            return
        out[r] = (digest(path), os.path.getsize(path))

    for fn in os.listdir(ROOT):  # pages and the manifest in the site root
        p = os.path.join(ROOT, fn)
        if os.path.isfile(p) and fn.endswith((".html", ".webmanifest")):
            add(p)
    for sub, only in (("assets", None), ("data", ".js"), ("theory", ".html"), ("anki_stuff", ".html")):
        for dp, dn, fns in os.walk(os.path.join(ROOT, sub)):
            dn[:] = [d for d in dn if d not in ("content", "__pycache__")]
            for fn in fns:
                if fn.startswith("."):
                    continue
                if only and not fn.endswith(only):
                    continue
                add(os.path.join(dp, fn))
    return out


def image_files():
    out = {}
    base = os.path.join(ROOT, "images")
    for dp, dn, fns in os.walk(base):
        for fn in fns:
            if fn.startswith(".") or os.path.splitext(fn)[1].lower() not in IMG_EXT:
                continue
            p = os.path.join(dp, fn)
            out[rel(p)] = (digest(p), os.path.getsize(p))
    return out


def pack_files(img):
    names = set()
    for s in load_atlas()["sets"]:
        for layer in s["layers"]:
            names.add(s["dir"].rstrip("/") + "/" + layer["file"])
    return sorted(n for n in names if n in img)


def render():
    core = core_files()
    img = image_files()
    pack = pack_files(img)
    version = hashlib.md5(
        json.dumps([sorted((k, v[0]) for k, v in core.items()), sorted((k, v[0]) for k, v in img.items())]).encode()
    ).hexdigest()[:10]
    data = {
        "v": version,
        "core": {k: core[k][0] for k in sorted(core)},
        "img": {k: img[k][0] for k in sorted(img)},
        "pack": pack,
        "coreBytes": sum(v[1] for v in core.values()),
        "packBytes": sum(img[k][1] for k in pack),
    }
    text = (
        "/* Generated by tools/build_pwa.py. Do not edit. */\n"
        "self.PWA = " + json.dumps(data, separators=(",", ":"), sort_keys=True) + ";\n"
    )
    return text, data


def build():
    text, data = render()
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return data


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if "--check" in argv:
        text, _ = render()
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("pwa-files.js is out of date. Run: python3 tools/build_theory.py")
            return 1
        print("pwa-files.js is up to date.")
        return 0
    d = build()
    print(
        "Offline files: %d core (%.1f MB), %d diagram layers (%.0f MB), version %s."
        % (len(d["core"]), d["coreBytes"] / 1048576, len(d["pack"]), d["packBytes"] / 1048576, d["v"])
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
